#!/usr/bin/env node
// Builds src/styles/tokens.css from design-tokens.md — the one file you edit to change the look.
//   node scripts/build-tokens.mjs          build once
//   node scripts/build-tokens.mjs --check  fail if tokens.css is out of date (CI)
// Also runs automatically before `npm run dev`, `npm run build` and `npm test`, and on every save
// of design-tokens.md while the dev server is running (see vite.config.js).
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
export const MD_PATH = join(root, 'design-tokens.md');
export const CSS_PATH = join(root, 'src/styles/tokens.css');

const SECTIONS = { foundations: 'Foundations', light: 'Light theme', dark: 'Dark theme', components: 'Components' };

/** Parse design-tokens.md into { foundations, light, dark, components }: each a list of groups with rows. */
export function parseMarkdown(text) {
  const out = { foundations: [], light: [], dark: [], components: [] };
  const errors = [];
  let section = null; let group = null;
  text.split('\n').forEach((raw, i) => {
    const line = raw.trim(); const at = `design-tokens.md:${i + 1}`;
    const h2 = line.match(/^##\s+(.+?)\s*$/);
    if (h2 && !line.startsWith('###')) {
      section = Object.keys(SECTIONS).find((k) => SECTIONS[k].toLowerCase() === h2[1].toLowerCase()) || null;
      group = null;
      return;
    }
    const h3 = line.match(/^###\s+(.+?)\s*$/);
    if (h3 && section) { group = { title: h3[1], rows: [] }; out[section].push(group); return; }
    if (!section || !line.startsWith('|')) return;
    const cells = line.replace(/^\||\|$/g, '').split('|').map((c) => c.trim());
    if (/^-{3,}/.test(cells[0].replace(/:/g, '')) || /^token$/i.test(cells[0])) return; // header / separator row
    const name = cells[0].replace(/`/g, '');
    const value = (cells[1] || '').replace(/`/g, '').trim();
    const note = (cells[2] || '').replace(/`/g, '').trim();
    if (!/^--[a-z0-9-]+$/.test(name)) { errors.push(`${at}: "${cells[0]}" is not a token name (use --like-this)`); return; }
    if (!value) { errors.push(`${at}: ${name} has no value`); return; }
    if (/[;{}]/.test(value)) { errors.push(`${at}: ${name} value must not contain ; { or }`); return; }
    if (!group) { group = { title: '', rows: [] }; out[section].push(group); }
    group.rows.push({ name, value, note, at });
  });
  return { tokens: out, errors };
}

/** Check names, duplicates and var() references. Returns a list of readable errors. */
export function validate(tokens) {
  const errors = [];
  const names = (sec) => tokens[sec].flatMap((g) => g.rows);
  const base = new Map();
  for (const sec of ['foundations', 'light', 'components']) {
    for (const r of names(sec)) {
      if (base.has(r.name)) errors.push(`${r.at}: ${r.name} is defined twice (also at ${base.get(r.name).at})`);
      else base.set(r.name, r);
    }
  }
  const darkSeen = new Map();
  for (const r of names('dark')) {
    if (darkSeen.has(r.name)) errors.push(`${r.at}: ${r.name} is defined twice in Dark theme`);
    darkSeen.set(r.name, r);
    if (!base.has(r.name)) errors.push(`${r.at}: ${r.name} only exists in Dark theme; add it to Light theme (or Foundations) first`);
  }
  for (const sec of Object.keys(SECTIONS)) {
    for (const r of names(sec)) {
      for (const m of r.value.matchAll(/var\((--[a-z0-9-]+)/g)) {
        if (!base.has(m[1]) && !darkSeen.has(m[1])) errors.push(`${r.at}: ${r.name} uses ${m[1]}, which isn't defined anywhere`);
      }
      const hex = r.value.match(/#[0-9a-fA-F]+\b/g) || [];
      for (const h of hex) if (![4, 7, 9].includes(h.length)) errors.push(`${r.at}: ${r.name} has a broken colour "${h}" (use #RGB, #RRGGBB or #RRGGBBAA)`);
    }
  }
  if (!names('foundations').length || !names('light').length) errors.push('design-tokens.md needs "## Foundations" and "## Light theme" sections with token tables');
  return errors;
}

const decl = (r, indent) => `${indent}${r.name}: ${r.value};${r.note ? ` /* ${r.note.replace(/\*\//g, '* /')} */` : ''}`;
const groups = (list, indent, extra = []) => [
  ...extra.map((e) => `${indent}${e}`),
  ...list.flatMap((g, i) => [...(g.title ? [`${i || extra.length ? '\n' : ''}${indent}/* ── ${g.title} ── */`] : []), ...g.rows.map((r) => decl(r, indent))]),
].join('\n');

/** Render the CSS. Dark is written twice from the same rows, so the two dark blocks can never drift. */
export function render(tokens) {
  return `/* GENERATED from design-tokens.md by scripts/build-tokens.mjs — do not edit this file.
   Change a value in frontend/design-tokens.md instead; the dev server rebuilds this on save.
   Layers (one-way references): 1. Foundations (brand primitives, type, spacing…) → 2. Light / Dark theme roles → 3. Components. */

/* ───────────── 1. Foundations ───────────── */
:root {
${groups(tokens.foundations, '  ')}
}

/* ───────────── 2. Light theme ───────────── */
:root {
${groups(tokens.light, '  ', ['color-scheme: light;'])}
}

/* ───────────── 2b. Dark theme (chosen in My settings, or following the system) ───────────── */
:root[data-theme='dark'] {
${groups(tokens.dark, '  ', ['color-scheme: dark;'])}
}
@media (prefers-color-scheme: dark) {
  :root:not([data-theme='light']) {
${groups(tokens.dark, '    ', ['color-scheme: dark;'])}
  }
}

/* ───────────── 3. Components ───────────── */
:root {
${groups(tokens.components, '  ')}
}

@media (prefers-reduced-motion: reduce) {
  :root { --dur-fast: 0ms; --dur-normal: 0ms; --dur-slow: 0ms; }
}
`;
}

/** Build tokens.css. Returns { ok, changed, errors }. Never writes a half-valid file. */
export function build({ check = false, quiet = false } = {}) {
  const log = quiet ? () => {} : (m) => console.log(m);
  if (!existsSync(MD_PATH)) return { ok: false, errors: [`Missing ${MD_PATH}`] };
  const { tokens, errors: parseErrors } = parseMarkdown(readFileSync(MD_PATH, 'utf8'));
  const errors = [...parseErrors, ...validate(tokens)];
  if (errors.length) return { ok: false, errors };
  const css = render(tokens);
  const current = existsSync(CSS_PATH) ? readFileSync(CSS_PATH, 'utf8') : '';
  if (check) return current === css ? { ok: true, changed: false, errors: [] } : { ok: false, errors: ['src/styles/tokens.css is out of date: run `npm run tokens`'] };
  if (current !== css) { writeFileSync(CSS_PATH, css); log(`tokens: wrote src/styles/tokens.css from design-tokens.md (${Object.values(tokens).flat().reduce((n, g) => n + g.rows.length, 0)} tokens)`); }
  return { ok: true, changed: current !== css, errors: [] };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const res = build({ check: process.argv.includes('--check') });
  if (!res.ok) { console.error(`tokens: design-tokens.md has ${res.errors.length} problem(s):\n  - ${res.errors.join('\n  - ')}`); process.exit(1); }
}
